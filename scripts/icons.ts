// Copies the page's line icons out of Lucide (ISC License) into status-page/src/icons: one .svg per icon, and index.tsx
// with the same drawings as React components at a 1.5 stroke. The page then loads no icon library. Run after changing
// the list: node scripts/icons.ts (needs lucide-react installed; it is a dev dependency only for this).
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS: Readonly<Record<string, string>> = {
  CheckCircle: "circle-check", AlertTriangle: "triangle-alert", XCircle: "circle-x", HelpCircle: "circle-question-mark", Wrench: "wrench",
  ChevronDown: "chevron-down", ChevronUp: "chevron-up", Sun: "sun", Moon: "moon", Lock: "lock-keyhole", LogOut: "log-out", Refresh: "rotate-cw",
  Clock: "clock", Megaphone: "megaphone", CalendarClock: "calendar-clock", Info: "info", Activity: "activity", ArrowLeft: "arrow-left",
};
const dir = join(import.meta.dirname, "..", "status-page", "src", "icons");
const lucide = join(import.meta.dirname, "..", "node_modules", "lucide-react", "dist", "esm", "icons");
const jsxName = (key: string): string => key.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());

let index = `// Line icons from Lucide (https://lucide.dev, ISC License, Copyright (c) Lucide Contributors), stored here as SVG
// (the .svg files beside this one) so the page loads no icon library. Generated by scripts/icons.ts: edit the list there.
// Each takes currentColor at a 1.5 stroke and is hidden from assistive technology: it always sits next to words.
import type { SVGProps } from "react";

export type Icon = (props: SVGProps<SVGSVGElement>) => React.JSX.Element;

function svg(children: React.ReactNode, { className, ...props }: SVGProps<SVGSVGElement>): React.JSX.Element {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.5} strokeLinecap="round"
      strokeLinejoin="round" aria-hidden="true" focusable="false" className={className ?? "size-4"} {...props}>
      {children}
    </svg>
  );
}

`;
for (const [component, file] of Object.entries(ICONS)) {
  const module: unknown = await import(join(lucide, `${file}.mjs`));
  const data: unknown = typeof module === "object" && module !== null ? Reflect.get(module, "__iconData") : null;
  const node: unknown = typeof data === "object" && data !== null ? Reflect.get(data, "node") : null;
  if (!Array.isArray(node)) throw new Error(`ICON_MISSING:${file}`);
  const elements = node.map((entry: unknown) => {
    const tag: unknown = Array.isArray(entry) ? entry[0] : null, props: unknown = Array.isArray(entry) ? entry[1] : null;
    if (typeof tag !== "string" || typeof props !== "object" || props === null) throw new Error(`ICON_SHAPE:${file}`);
    const attributes = Object.entries(props).filter(([name]) => name !== "key").map(([name, value]: [string, unknown]) => [name, String(value)] as const);
    return { tag, attributes };
  });
  const svgBody = elements.map(({ tag, attributes }) => `<${tag} ${attributes.map(([name, value]) => `${name}="${value}"`).join(" ")}/>`).join("");
  writeFileSync(join(dir, `${file}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" `
    + `stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${svgBody}</svg>\n`);
  const jsx = elements.map(({ tag, attributes }) => `<${tag} ${attributes.map(([name, value]) => `${jsxName(name)}="${value}"`).join(" ")} />`).join("");
  index += `export const ${component}: Icon = (props) => svg(<>${jsx}</>, props);\n`;
}
writeFileSync(join(dir, "index.tsx"), index);
console.log(`Icons written: ${String(Object.keys(ICONS).length)}`);
